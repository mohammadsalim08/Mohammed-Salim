export function calculateDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

export function formatWhatsAppUrl(rawPhone: string, businessName: string): string | null {
  if (!rawPhone) return null;
  const digitsOnly = rawPhone.replace(/\D/g, '');
  if (!digitsOnly || digitsOnly.length < 10) return null;

  let cleanNumber = digitsOnly;
  if (digitsOnly.length === 10) {
    cleanNumber = `91${digitsOnly}`;
  } else if (digitsOnly.length === 11 && digitsOnly.startsWith('0')) {
    cleanNumber = `91${digitsOnly.slice(1)}`;
  } else if (!digitsOnly.startsWith('91') && digitsOnly.length > 10) {
    cleanNumber = `91${digitsOnly.slice(-10)}`;
  }

  const message = `Hello${businessName ? ` ${businessName}` : ''}, I found your business on VizagConnect. I would like to know more.`;
  return `https://wa.me/${cleanNumber}?text=${encodeURIComponent(message)}`;
}

export function formatTelUrl(rawPhone: string): string | null {
  if (!rawPhone) return null;
  const digits = rawPhone.replace(/[^\d+]/g, '');
  if (!digits || digits.replace(/\D/g, '').length < 6) return null;
  return `tel:${digits}`;
}

export function formatDirectionsUrl(biz: {
  name: string;
  address?: string;
  area?: string;
  latitude?: number;
  longitude?: number;
}): string | null {
  if (typeof biz.latitude === 'number' && typeof biz.longitude === 'number' && !isNaN(biz.latitude) && !isNaN(biz.longitude)) {
    return `https://www.google.com/maps/dir/?api=1&destination=${biz.latitude},${biz.longitude}`;
  }
  if (biz.address && biz.address.trim()) {
    const destinationQuery = `${biz.name}, ${biz.address}, Visakhapatnam, Andhra Pradesh`;
    return `https://www.google.com/maps/dir/?api=1&destination=${encodeURIComponent(destinationQuery)}`;
  }
  return null;
}

